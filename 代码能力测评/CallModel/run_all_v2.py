PROMPT_TEMPLATE = """\
你是一个严谨的 Python 算法答题助手。请按图片中的 LeetCode 题目要求作答。

当前题号：{question_id}

请阅读图片里的题目描述、示例、提示，以及图片底部给出的 Python 函数接口。
生成满足题意的 Python 代码，要求如下：
1. 只输出 Python 代码，不要解释，不要 Markdown。
2. 必须实现一个函数，函数名必须是 question_{question_id}。
3. 函数参数和返回值必须与图片中的 Python 函数接口一致。
4. 不要输出 class Solution，也不要输出测试代码。
5. 可以使用 Python 标准库；如需类型标注，可以使用 List、Optional 等。
6. 如果题目要求原地修改输入对象，请按题意原地修改并保持返回值约定。

最终输出格式示例：
def question_{question_id}(...):
    ...
"""


def sanitize_identifier(value: str) -> str:
    value = re.sub(r"\W+", "_", value.strip(), flags=re.UNICODE).strip("_")
    if not value:
        value = "model"
    if value[0].isdigit():
        value = "model_" + value
    return value


def class_name_for_model(model: str) -> str:
    return f"{sanitize_identifier(model)}_codingtest"


def normalize_base_url(base_url: str) -> str:
    base_url = base_url.rstrip("/")
    if base_url.endswith("/chat/completions"):
        return base_url[: -len("/chat/completions")]
    return base_url


def resolve_base_url(args: argparse.Namespace) -> str:
    if args.base_url:
        return normalize_base_url(args.base_url)
    if not args.host or args.port is None:
        raise ValueError("请传入 --base-url，或同时传入 --host 和 --port")
    host = args.host.strip()
    if host.startswith("http://") or host.startswith("https://"):
        base = host.rstrip("/")
    else:
        base = f"{args.scheme}://{host}:{args.port}"
    if not base.endswith("/v1"):
        base = base.rstrip("/") + "/v1"
    return normalize_base_url(base)


def image_to_data_url(path: Path) -> str:
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:image/jpeg;base64,{data}"


def sorted_question_images(image_dir: Path) -> List[Tuple[int, Path]]:
    pairs: List[Tuple[int, Path]] = []
    for path in image_dir.glob("question_*.jpg"):
        match = re.fullmatch(r"question_(\d+)\.jpg", path.name)
        if match:
            pairs.append((int(match.group(1)), path))
    pairs.sort(key=lambda item: item[0])
    return pairs


def parse_question_filter(raw: str) -> Optional[set[int]]:
    if not raw:
        return None
    result: set[int] = set()
    for piece in raw.split(","):
        piece = piece.strip()
        if not piece:
            continue
        if "-" in piece:
            left, right = piece.split("-", 1)
            start, end = int(left), int(right)
            result.update(range(min(start, end), max(start, end) + 1))
        else:
            result.add(int(piece))
    return result


def build_messages(question_id: int, image_path: Path) -> List[dict]:
    return [
        {
            "role": "user",
            "content": [
                {"type": "text", "text": PROMPT_TEMPLATE.format(question_id=question_id)},
                {
                    "type": "image_url",
                    "image_url": {
                        "url": image_to_data_url(image_path),
                    },
                },
            ],
        }
    ]


def call_openai_compatible_api(
    *,
    base_url: str,
    api_key: str,
    model: str,
    messages: List[dict],
    temperature: float,
    max_tokens: int,
    timeout: int,
) -> str:
    url = normalize_base_url(base_url) + "/chat/completions"
    payload = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "max_tokens": max_tokens,
    }
    body = json.dumps(payload).encode("utf-8")
    request = Request(
        url,
        data=body,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
        },
        method="POST",
    )
    try:
        with urlopen(request, timeout=timeout) as response:
            data = json.loads(response.read().decode("utf-8"))
    except HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"API HTTP {exc.code}: {detail}") from exc
    except URLError as exc:
        raise RuntimeError(f"API connection failed: {exc}") from exc

    try:
        content = data["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise RuntimeError(f"Unexpected API response: {json.dumps(data, ensure_ascii=False)[:1000]}") from exc
    if isinstance(content, list):
        return "\n".join(part.get("text", "") for part in content if isinstance(part, dict))
    return str(content)


def strip_markdown_fences(text: str) -> str:
    text = text.strip()
    blocks = re.findall(r"```(?:python|py)?\s*(.*?)```", text, flags=re.IGNORECASE | re.DOTALL)
    if blocks:
        return strip_model_special_tokens(max(blocks, key=len).strip())
    text = re.sub(r"^```(?:python|py)?\s*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s*```$", "", text)
    return strip_model_special_tokens(text.strip())


def strip_model_special_tokens(text: str) -> str:
    # Some local models append generation sentinels as plain text; Python cannot parse them.
    for token in ("<eos>", "<end_of_turn>", "<|end|>", "<|eot_id|>", "</s>"):
        index = text.find(token)
        if index != -1:
            text = text[:index]
    return text.strip()


def extract_function_code(raw_text: str, question_id: int) -> str:
    function_name = f"question_{question_id}"
    errors: List[str] = []
    for code in code_candidates(raw_text):
        module = parse_python_module(code)
        if module is None:
            errors.append("候选代码不是完整 Python 语法")
            continue
        node = find_named_function(module, function_name)
        if node is None:
            errors.append(f"候选代码里没有找到 {function_name}")
            continue
        return source_for_node(code, node)
    detail = "; ".join(errors[-3:]) if errors else "没有找到可解析的 Python 代码"
    raise ValueError(detail)


def code_candidates(raw_text: str) -> List[str]:
    raw_text = normalize_model_text(raw_text)
    candidates: List[str] = []

    for block in fenced_code_blocks(raw_text):
        add_code_candidate(candidates, block)

    decoded = maybe_json_code(raw_text)
    if decoded and decoded != raw_text:
        add_code_candidate(candidates, decoded)
        for block in fenced_code_blocks(decoded):
            add_code_candidate(candidates, block)

    add_code_candidate(candidates, raw_text)
    return candidates


def normalize_model_text(text: str) -> str:
    return str(text or "").replace("\r\n", "\n").replace("\r", "\n").replace("\x00", "").strip()


def fenced_code_blocks(text: str) -> List[str]:
    blocks: List[Tuple[int, int, str]] = []
    pattern = re.compile(r"```([A-Za-z0-9_-]*)[^\n]*\n(.*?)```", flags=re.DOTALL)
    for match in pattern.finditer(text):
        lang = match.group(1).lower()
        body = match.group(2)
        priority = 0 if lang in {"python", "py", ""} else 1
        if "def " in body or "class " in body:
            blocks.append((priority, match.start(), body))
    blocks.sort(key=lambda item: (item[0], item[1]))
    return [body for _, _, body in blocks]


def maybe_json_code(text: str) -> Optional[str]:
    stripped = text.strip()
    if not stripped.startswith(("{", "[")):
        return None
    try:
        payload = json.loads(stripped)
    except Exception:
        return None
    stack = [payload]
    keys = ("code", "python", "answer", "output", "content", "solution")
    while stack:
        item = stack.pop(0)
        if isinstance(item, dict):
            for key in keys:
                value = item.get(key)
                if isinstance(value, str) and ("def " in value or "class " in value):
                    return value
            stack.extend(item.values())
        elif isinstance(item, list):
            stack.extend(item)
    return None


def add_code_candidate(candidates: List[str], text: str) -> None:
    for candidate in candidate_variants(text):
        candidate = candidate.strip()
        if candidate and candidate not in candidates:
            candidates.append(candidate)
        dedented = textwrap.dedent(candidate).strip()
        if dedented and dedented not in candidates:
            candidates.append(dedented)


def candidate_variants(text: str) -> List[str]:
    text = strip_outer_noise(normalize_model_text(text))
    variants = [text]
    prefix = longest_parseable_prefix(text)
    if prefix and prefix != text:
        variants.append(prefix)

    lines = text.splitlines()
    for index, line in enumerate(lines):
        if is_likely_code_start(line):
            tail = "\n".join(lines[index:]).strip()
            if tail:
                variants.append(tail)
                prefix = longest_parseable_prefix(tail)
                if prefix and prefix != tail:
                    variants.append(prefix)
            break
    return variants


def strip_outer_noise(text: str) -> str:
    lines = text.strip().splitlines()
    while lines and lines[0].strip().lower() in {"python", "py"}:
        lines.pop(0)
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped in {"<eos>", "<end_of_turn>", "<|end|>", "<|eot_id|>", "</s>"}:
            lines = lines[:index]
            break
    return "\n".join(lines).strip()


def is_likely_code_start(line: str) -> bool:
    stripped = line.lstrip()
    return bool(
        re.match(
            r"^(from\s+\S+\s+import\s+|import\s+|class\s+|def\s+|async\s+def\s+|@)",
            stripped,
        )
    )


def longest_parseable_prefix(text: str) -> Optional[str]:
    lines = text.strip().splitlines()
    for end in range(len(lines), 0, -1):
        candidate = "\n".join(lines[:end]).strip()
        if not candidate:
            continue
        try:
            ast.parse(candidate)
            return candidate
        except SyntaxError:
            continue
    return None


def parse_python_module(code: str) -> Optional[ast.Module]:
    try:
        return ast.parse(code)
    except SyntaxError:
        return None


def find_named_function(module: ast.Module, function_name: str) -> Optional[ast.AST]:
    parent: Dict[ast.AST, ast.AST] = {}
    for node in ast.walk(module):
        for child in ast.iter_child_nodes(node):
            parent[child] = node
    candidates: List[ast.AST] = []
    for node in ast.walk(module):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == function_name:
            owner = parent.get(node)
            if isinstance(owner, (ast.Module, ast.ClassDef)):
                candidates.append(node)
    if not candidates:
        return None
    return sorted(candidates, key=lambda item: item.lineno)[-1]


def source_for_node(code: str, node: ast.AST) -> str:
    lines = code.splitlines()
    start = getattr(node, "lineno") - 1
    decorator_list = getattr(node, "decorator_list", [])
    if decorator_list:
        start = min(getattr(deco, "lineno") - 1 for deco in decorator_list)
    end = getattr(node, "end_lineno", getattr(node, "lineno"))
    return textwrap.dedent("\n".join(lines[start:end])).strip()


def indent_method(function_code: str) -> str:
    return textwrap.indent(function_code.strip(), "    ") + "\n"


def placeholder_method(question_id: int, reason: str) -> str:
    safe_reason = str(reason).replace("\n", " ").replace("\r", " ").strip()
    if len(safe_reason) > 240:
        safe_reason = safe_reason[:240] + "..."
    return "\n".join(
        [
            f"def question_{question_id}(self):",
            f"    # {safe_reason}",
            "    pass",
        ]
    )


def load_existing_methods(answer_file: Path, class_name: str) -> Dict[int, str]:
    if not answer_file.exists():
        return {}
    code = answer_file.read_text(encoding="utf-8")
    try:
        tree = ast.parse(code)
    except SyntaxError:
        raise RuntimeError(f"现有答案文件语法错误，无法安全合并：{answer_file}")

    methods: Dict[int, str] = {}
    lines = code.splitlines()
    target_class = None
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == class_name:
            target_class = node
            break
    if target_class is None:
        return methods

    for node in target_class.body:
        if isinstance(node, ast.FunctionDef):
            match = re.fullmatch(r"question_(\d+)", node.name)
            if match:
                snippet = "\n".join(lines[node.lineno - 1 : getattr(node, "end_lineno", node.lineno)])
                methods[int(match.group(1))] = textwrap.dedent(snippet).strip()
    return methods


def write_answer_file(answer_file: Path, class_name: str, methods: Dict[int, str]) -> None:
    content = [ANSWER_FILE_HEADER, f"class {class_name}:\n"]
    if not methods:
        content.append("    pass\n")
    else:
        for question_id in sorted(methods):
            content.append(indent_method(methods[question_id]))
            content.append("\n")
    answer_file.write_text("".join(content).rstrip() + "\n", encoding="utf-8")


def append_log(log_file: Path, record: dict) -> None:
    with log_file.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, ensure_ascii=False) + "\n")


def resolve_path(path_value: str | Path, base_dir: Path = SCRIPT_DIR) -> Path:
    path = Path(path_value).expanduser()
    if path.is_absolute():
        return path
    return base_dir / path


def format_duration(seconds: float) -> str:
    if seconds < 60:
        return f"{seconds:.2f}s"
    minutes, remainder = divmod(seconds, 60)
    if minutes < 60:
        return f"{int(minutes)}m{remainder:.2f}s"
    hours, minutes = divmod(minutes, 60)
    return f"{int(hours)}h{int(minutes)}m{remainder:.2f}s"


def run(args: argparse.Namespace) -> int:
    args.resolved_base_url = resolve_base_url(args)
    image_dir = resolve_path(args.images_dir)
    output_dir = resolve_path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    class_name = class_name_for_model(args.model)
    answer_file = resolve_path(args.output_file) if args.output_file else output_dir / f"{class_name}.py"
    log_file = output_dir / f"{class_name}.jsonl"

    images = sorted_question_images(image_dir)
    if not images:
        raise RuntimeError(f"没有找到题目图片：{image_dir}/question_*.jpg")
    selected = parse_question_filter(args.questions)
    if selected is not None:
        images = [(qid, path) for qid, path in images if qid in selected]

    methods = load_existing_methods(answer_file, class_name)
    write_answer_file(answer_file, class_name, methods)

    print(f"model: {args.model}")
    print(f"api: {args.resolved_base_url}/chat/completions")
    print(f"images: {image_dir}")
    print(f"answer: {answer_file}")
    print(f"class: {class_name}")
    total_generation_seconds = 0.0
    timed_questions = 0

    for index, (question_id, image_path) in enumerate(images, 1):
        if question_id in methods and not args.force:
            print(f"[{index:03d}/{len(images)}] skip question_{question_id} (already exists)")
            continue

        print(f"[{index:03d}/{len(images)}] call model for question_{question_id}")
        messages = build_messages(question_id, image_path)
        started = time.perf_counter()
        try:
            raw = call_with_retry(
                args=args,
                messages=messages,
                question_id=question_id,
            )
        except Exception as exc:
            elapsed = time.perf_counter() - started
            total_generation_seconds += elapsed
            timed_questions += 1
            method_code = placeholder_method(question_id, f"模型调用失败或超时：{exc}")
            methods[question_id] = method_code
            write_answer_file(answer_file, class_name, methods)
            append_log(
                log_file,
                {
                    "question_id": question_id,
                    "status": "api_failed",
                    "error": str(exc),
                    "generation_seconds": round(elapsed, 6),
                    "method": method_code,
                },
            )
            print(
                f"[{index:03d}/{len(images)}] saved placeholder for question_{question_id} "
                f"(api_failed, generation_time={format_duration(elapsed)})"
            )
            continue
        elapsed = time.perf_counter() - started
        total_generation_seconds += elapsed
        timed_questions += 1

        try:
            method_code = extract_function_code(raw, question_id)
            ast.parse("class _T:\n" + indent_method(method_code))
        except Exception as exc:
            method_code = placeholder_method(question_id, f"模型返回格式错误：{exc}")
            methods[question_id] = method_code
            write_answer_file(answer_file, class_name, methods)
            append_log(
                log_file,
                {
                    "question_id": question_id,
                    "status": "parse_failed",
                    "error": str(exc),
                    "generation_seconds": round(elapsed, 6),
                    "raw": raw,
                    "method": method_code,
                },
            )
            print(
                f"[{index:03d}/{len(images)}] saved placeholder for question_{question_id} "
                f"(parse_failed, generation_time={format_duration(elapsed)})"
            )
            continue

        methods[question_id] = method_code
        write_answer_file(answer_file, class_name, methods)
        append_log(
            log_file,
            {
                "question_id": question_id,
                "status": "ok",
                "generation_seconds": round(elapsed, 6),
                "method": method_code,
            },
        )
        print(f"[{index:03d}/{len(images)}] saved question_{question_id} (generation_time={format_duration(elapsed)})")

    print(f"done: {answer_file}")
    append_log(
        log_file,
        {
            "status": "summary",
            "total_generation_seconds": round(total_generation_seconds, 6),
            "counted_questions": timed_questions,
            "formatted_total_generation_time": format_duration(total_generation_seconds),
        },
    )
    print(
        f"total_generation_time: {format_duration(total_generation_seconds)} "
        f"({total_generation_seconds:.2f}s, counted_questions={timed_questions})"
    )
    return 0


def call_with_retry(args: argparse.Namespace, messages: List[dict], question_id: int) -> str:
    last_error: Optional[Exception] = None
    for attempt in range(1, args.retries + 2):
        try:
            return call_openai_compatible_api(
                base_url=args.resolved_base_url,
                api_key=args.api_key,
                model=args.model,
                messages=messages,
                temperature=args.temperature,
                max_tokens=args.max_tokens,
                timeout=args.timeout,
            )
        except Exception as exc:
            last_error = exc
            if attempt > args.retries:
                break
            wait = min(30, 2 * attempt)
            print(f"question_{question_id} API failed: {exc}; retry in {wait}s", file=sys.stderr)
            time.sleep(wait)
    raise RuntimeError(f"question_{question_id} API 调用失败：{last_error}") from last_error


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Call an OpenAI-compatible model with question images and build a coding test class."
    )
    parser.add_argument("--model", required=True, help="模型名，例如 gemma-4-E4B-it-MLX-4bit")
    parser.add_argument("--base-url", default="", help="OpenAI compatible base url，例如 http://127.0.0.1:8999/v1")
    parser.add_argument("--scheme", default="http", choices=["http", "https"], help="未传 --base-url 时用于拼接 API 地址")
    parser.add_argument("--host", default="", help="未传 --base-url 时使用的主机，例如 127.0.0.1")
    parser.add_argument("--port", type=int, default=None, help="未传 --base-url 时使用的端口，例如 8999")
    parser.add_argument("--api-key", default=DEFAULT_API_KEY, help="API key；也可通过 OMLX_API_KEY 或 OPENAI_API_KEY 设置")
    parser.add_argument("--images-dir", default="代码题目", help="题目图片目录；相对路径按 run_all_v2.py 所在目录解析")
    parser.add_argument("--output-dir", default="result", help="答案文件输出目录；相对路径按 run_all_v2.py 所在目录解析，默认：result")
    parser.add_argument("--output-file", default="", help="指定答案文件路径；相对路径按 run_all_v2.py 所在目录解析")
    parser.add_argument("--questions", default="", help="只处理部分题号，例如 1,2,48 或 1-20；默认处理全部图片")
    parser.add_argument("--temperature", type=float, default=0.0)
    parser.add_argument("--max-tokens", type=int, default=4096)
    parser.add_argument("--timeout", type=int, default=180)
    parser.add_argument("--retries", type=int, default=2)
    parser.add_argument("--force", action="store_true", help="已存在 question_题号 时重新调用并覆盖")
    return parser


def main() -> int:
    parser = build_arg_parser()
    args = parser.parse_args()
    try:
        return run(args)
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
